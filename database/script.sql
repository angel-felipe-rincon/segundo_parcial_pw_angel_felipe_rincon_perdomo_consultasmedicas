CREATE TABLE IF NOT EXISTS roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(45) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS medicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL,
    especialidad VARCHAR(45) NOT NULL
);

CREATE TABLE IF NOT EXISTS usuarios (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(45) NOT NULL UNIQUE,
    password VARCHAR(60) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    nombre VARCHAR(40),
    medico_id BIGINT REFERENCES medicos (id)
);

CREATE TABLE IF NOT EXISTS usuarios_roles (
    user_id BIGINT NOT NULL REFERENCES usuarios (user_id),
    role_id BIGINT NOT NULL REFERENCES roles (role_id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS consultas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_paciente VARCHAR(40) NOT NULL,
    motivo VARCHAR(100) NOT NULL,
    numero_consultorio INTEGER NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    medico_id BIGINT NOT NULL REFERENCES medicos (id)
);

